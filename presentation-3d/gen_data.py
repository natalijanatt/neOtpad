import csv, json, io

D = "../waste-scraper/data/"
def rd(p):
    return list(csv.DictReader(io.open(D+p, encoding="utf-8-sig")))

nas = rd("pirot_naselja.csv")
def num(v, d=None):
    try: return int(v)
    except: 
        try: return float(v)
        except: return d

villages = []
for r in nas:
    villages.append({
        "n": r["naziv"],
        "lat": float(r["lat"]), "lon": float(r["lon"]),
        "hh": num(r["broj_domacinstava"]),            # households
        "pop": num(r["broj_stanovnika_2011"]),
        "k": num(r["broj_kontejnera_1100l"]),          # 1100 l containers on record
        "w": num(r["odvoz_nedeljno"]),                 # pickups per week (2018)
        "cov": r["organizovano_prikupljanje"] == "da",
        "city": r["kategorija_lpuo"] == "grad",
    })

# canonical illegal dumps; drop the Eko Alert default coordinate (= "unknown location")
DEFAULT_LAT, DEFAULT_LON = 43.1682819, 22.5956678
dumps = []
for r in rd("pirot_divlje_deponije_kanonske.csv"):
    if not r["lat"] or not r["lon"]: continue
    lat, lon = float(r["lat"]), float(r["lon"])
    if abs(lat-DEFAULT_LAT) < 1e-4 and abs(lon-DEFAULT_LON) < 1e-4: continue
    dumps.append({
        "id": r["kanonski_id"], "n": r["naselje"], "lat": lat, "lon": lon,
        "prec": r["geo_preciznost"],
        "rec": r["ponovo_se_stvara"] == "da",
        "obs": num(r["broj_opservacija"], 1),
        "y0": num(r["prvi_put_zabelezena"]), "y1": num(r["poslednji_put_zabelezena"]),
    })

out = {"villages": villages, "dumps": dumps}
io.open("src/data.js", "w", encoding="utf8").write(
    "// generated by gen_data.py from waste-scraper/data/ - do not hand-edit\n"
    "export default " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")

cov = sum(1 for v in villages if v["cov"])
print("villages", len(villages), "covered", cov, "uncovered", len(villages)-cov)
print("containers on record", sum(v["k"] or 0 for v in villages))
print("households", sum(v["hh"] or 0 for v in villages))
print("dumps kept", len(dumps), "recurring", sum(1 for d in dumps if d["rec"]),
      "precise", sum(1 for d in dumps if d["prec"]=="registarska_tacka"))
