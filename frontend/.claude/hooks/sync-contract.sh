#!/usr/bin/env bash
#
# SessionStart hook.
#
# Brings the API contract up to date and regenerates the typed client from it,
# then reports the contract version into the session context. The backend is
# written on a different machine, so without this a session can spend its whole
# length generating code against a contract that moved yesterday.
#
# Never blocks: a session that cannot reach the remote is still a usable
# session, it just says so.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FRONTEND_DIR="$(cd "${SCRIPT_DIR}/../.." && pwd)"
REPO_ROOT="$(cd "${FRONTEND_DIR}/.." && pwd)"
SPEC_PATH="${REPO_ROOT}/contracts/openapi.json"

NOTES=""
note() { NOTES="${NOTES}$1"$'\n'; }

emit() {
  # SessionStart hooks add to the session context via additionalContext.
  node -e '
    const context = process.argv[1];
    process.stdout.write(JSON.stringify({
      hookSpecificOutput: {
        hookEventName: "SessionStart",
        additionalContext: context,
      },
    }));
  ' "$1"
  exit 0
}

if ! command -v node >/dev/null 2>&1; then
  emit "Contract sync did not run: node is not on PATH. The generated API client in src/api/generated/ may be out of date with contracts/openapi.json."
fi

# --- 1. fetch, and fast-forward only when that is unambiguously safe ---------
cd "${REPO_ROOT}"

if git rev-parse --git-dir >/dev/null 2>&1 && git remote get-url origin >/dev/null 2>&1; then
  if git fetch origin --quiet 2>/dev/null; then
    BRANCH="$(git rev-parse --abbrev-ref HEAD)"
    UPSTREAM="origin/${BRANCH}"
    if git rev-parse --verify --quiet "${UPSTREAM}" >/dev/null; then
      BEHIND="$(git rev-list --count "HEAD..${UPSTREAM}")"
      if [ "${BEHIND}" != "0" ]; then
        if [ -z "$(git status --porcelain)" ]; then
          if git merge --ff-only "${UPSTREAM}" --quiet 2>/dev/null; then
            note "Fast-forwarded ${BRANCH} to ${UPSTREAM} (${BEHIND} commit(s))."
          else
            note "${BRANCH} is ${BEHIND} commit(s) behind ${UPSTREAM} and could not be fast-forwarded. The contract below may be stale; running 'git pull' resolves it."
          fi
        else
          note "${BRANCH} is ${BEHIND} commit(s) behind ${UPSTREAM}, but the working tree has uncommitted changes so it was left alone. The contract below may be stale."
        fi
      fi
    fi
  else
    note "Could not reach origin. Working from the local checkout of the contract."
  fi
fi

# --- 2. regenerate the client from whatever contract we now have -------------
cd "${FRONTEND_DIR}"

if [ ! -f "${SPEC_PATH}" ]; then
  emit "contracts/openapi.json does not exist in this checkout, so the typed API client could not be generated. The backend generates that file; until it lands, there is no contract to build against."
fi

VERSION="$(node -e '
  const fs = require("fs");
  try {
    const spec = JSON.parse(fs.readFileSync(process.argv[1], "utf8"));
    process.stdout.write(String(spec?.info?.version ?? "unknown"));
  } catch {
    process.stdout.write("unreadable");
  }
' "${SPEC_PATH}")"

OPERATIONS="$(node -e '
  const fs = require("fs");
  try {
    const spec = JSON.parse(fs.readFileSync(process.argv[1], "utf8"));
    const methods = ["get", "put", "post", "delete", "patch"];
    const lines = [];
    for (const [route, item] of Object.entries(spec.paths ?? {})) {
      for (const method of methods) {
        if (item?.[method]) {
          lines.push(`  ${method.toUpperCase()} ${route} -> ${item[method].operationId ?? "(no operationId)"}`);
        }
      }
    }
    process.stdout.write(lines.join("\n") || "  (the contract defines no operations yet)");
  } catch {
    process.stdout.write("  (the contract could not be parsed)");
  }
' "${SPEC_PATH}")"

if [ -d node_modules ]; then
  if GEN_OUTPUT="$(npm run --silent api:generate 2>&1)"; then
    if git diff --quiet -- src/api/generated 2>/dev/null; then
      note "The generated client was already up to date with contract ${VERSION}."
    else
      note "The generated client in src/api/generated/ was regenerated and now differs from the last commit. Those changes belong in a commit of their own."
    fi
  else
    note "Regenerating the client failed:"$'\n'"${GEN_OUTPUT}"
  fi
else
  note "frontend/node_modules is missing, so the client was not regenerated. 'npm install' in frontend/ fixes it."
fi

# --- 3. report as project facts, not as orders ------------------------------
read -r -d '' CONTEXT <<CTX || true
API contract state for this session:

- The contract is contracts/openapi.json, version ${VERSION}. It is generated by
  the backend from its NestJS source and is the only description of the API this
  frontend can rely on.
- src/api/generated/ is generated from that contract by 'npm run api:generate'.
  Editing anything in that directory has no lasting effect: the next generation
  run overwrites it, and a PreToolUse hook rejects the edit before that.
- HTTP in this app goes through 'api' from src/api/client.ts, which is typed
  from the contract. Calls written with fetch or axios bypass that typing, so a
  route that does not exist on the backend would fail at runtime instead of at
  compile time.
- 'npm run mock' starts a Prism mock of the contract on port 4010, which is the
  client's default base URL. The backend does not need to be running.
- An endpoint the frontend needs but the contract does not define is a backend
  change. It cannot be added from this side.

Operations currently in the contract:
${OPERATIONS}

${NOTES}
CTX

emit "${CONTEXT}"
